    ["-J"] = { "合并全部行（不截断）" },
    ["--join-lines"] = { "合并全部行（不截断）" },
    ["-l"] = { " length", "页面行数（默认 66）" },
    ["--length"] = { " length", "页面行数（默认 66）" },
    ["-m"] = { "并行打印所有文件（每列一个文件）" },
    ["--merge"] = { "并行打印所有文件（每列一个文件）" },
    ["-n"] = { " separator,digits", "为每行添加行号" },
    ["--number-lines"] = { " separator,digits", "为每行添加行号" },
    ["-N"] = { " number-lines", "为每行添加行号" },
    ["-o"] = { " margin", "设置左缩进宽度" },
    ["--indent"] = { " margin", "设置左缩进宽度" },
    ["-r"] = { "禁止文件无法打开时的警告" },
    ["--no-file-warnings"] = { "禁止文件无法打开时的警告" },
    ["-s"] = { " separator", "设置列分隔符" },
    ["--separator"] = { " separator", "设置列分隔符" },
    ["-S"] = { " string", "设置列分隔字符串" },
    ["--sep-string"] = { " string", "设置列分隔字符串" },
    ["-t"] = { "省略页眉和页尾" },
    ["--omit-header"] = { "省略页眉和页尾" },
    ["-T"] = { "省略分页（忽略换页符）" },
