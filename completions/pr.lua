clink.argmatcher("pr")
:addarg(clink.filematches)
:adddescriptions({
    ["-a"] = { "跨列打印（而非顺序列印）" },
    ["--across"] = { "跨列打印（而非顺序列印）" },
    ["-c"] = { " delimiter", "显示控制字符（使用脱字符表示法）" },
    ["--show-control-chars"] = { " delimiter", "显示控制字符（使用脱字符表示法）" },
    ["-d"] = { "输出行间距加倍" },
    ["--double-space"] = { "输出行间距加倍" },
    ["-D"] = { " format", "设置日期格式" },
    ["--date-format"] = { " format", "设置日期格式" },
    ["-e"] = { " tab-width", "将制表符扩展为空格（指定制表符宽度）" },
    ["--expand-tabs"] = { " tab-width", "将制表符扩展为空格（指定制表符宽度）" },
    ["-f"] = { "使用换页符（而非换行符）分隔页面" },
    ["--form-feed"] = { "使用换页符（而非换行符）分隔页面" },
    ["-F"] = { "使用换页符（而非换行符）分隔页面（同 -f）" },
    ["-h"] = { " header", "设置页眉文字" },
    ["--header"] = { " header", "设置页眉文字" },
