    ["-v"] = { "以脱字符表示法显示不可打印字符" },
    ["--show-nonprinting"] = { "以脱字符表示法显示不可打印字符" },
    ["-w"] = { " width", "页面宽度（默认 72）" },
    ["--width"] = { " width", "页面宽度（默认 72）" },
    ["--help"] = { "显示帮助并退出" },
    ["--version"] = { "输出版本信息并退出" },
})
:addflags({
    "-a", "--across",
    "-c",
    "--show-control-chars=",
    "-d", "--double-space",
    "-D",
    "--date-format=",
    "-e"..num_arg,
    "--expand-tabs="..num_arg,
    "-f", "--form-feed",
    "-F",
    "-h",
    "--header=",
    "-i"..num_arg,
    "--output-tabs="..num_arg,
    "-J", "--join-lines",
    "-l"..num_arg,
    "--length="..num_arg,
    "-m", "--merge",
    "-n",
    "--number-lines=",
    "-N"..num_arg,
    "-o"..num_arg,
    "--indent="..num_arg,
    "-r", "--no-file-warnings",
    "-s",
    "--separator=",
