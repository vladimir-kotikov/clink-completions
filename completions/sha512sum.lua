--------------------------------------------------------------------------------
-- Clink argmatcher for sha512sum (uutils / GNU coreutils)
--

clink.argmatcher("sha512sum")
:addarg(clink.filematches)
:adddescriptions({
    ["-b"] = { "以二进制模式读取文件（默认自动检测）" },
    ["--binary"] = { "以二进制模式读取文件（默认自动检测）" },
    ["-c"] = { "从文件中读取校验和并进行校验" },
    ["--check"] = { "从文件中读取校验和并进行校验" },
    ["-t"] = { "以文本模式读取文件（默认）" },
    ["--text"] = { "以文本模式读取文件（默认）" },
    ["--tag"] = { "使用 BSD 风格的输出格式" },
    ["-q"] = { "校验时不在标准输出显示 OK" },
    ["--quiet"] = { "校验时不在标准输出显示 OK" },
    ["-s"] = { "不输出任何内容，仅通过退出码指示结果" },
    ["--status"] = { "不输出任何内容，仅通过退出码指示结果" },
    ["--warn"] = { "对格式错误的校验和行发出警告" },
    ["--strict"] = { "遇到格式错误的校验和行时以非零退出码退出" },
    ["--ignore-missing"] = { "校验时不报告缺失文件的状态" },
    ["-z"] = { "在输出行结尾使用 NUL 分隔而非换行符" },
    ["--zero"] = { "在输出行结尾使用 NUL 分隔而非换行符" },
    ["--help"] = { "显示帮助并退出" },
    ["--version"] = { "输出版本信息并退出" },
})
:addflags({
    "-b", "--binary",
    "-c", "--check",
    "-t", "--text",
    "--tag",
    "-q", "--quiet",
    "-s", "--status",
    "--warn",
    "--strict",
    "--ignore-missing",
    "-z", "--zero",
    "--help", "--version",
})
