--------------------------------------------------------------------------------
-- Clink argmatcher for ls (GNU coreutils)
--

clink.argmatcher("ls")
:addarg(clink.dirmatches)
:adddescriptions({
    ["-a"] = { "不忽略以 . 开头的条目" },
    ["--all"] = { "不忽略以 . 开头的条目" },
    ["-A"] = { "不列出隐含的 . 和 .." },
    ["--almost-all"] = { "不列出隐含的 . 和 .." },
    ["-l"] = { "使用长列表格式" },
    ["-h"] = { "以人类可读的格式打印大小（例如 1K 234M 2G）" },
    ["--human-readable"] = { "以人类可读的格式打印大小" },
    ["-r"] = { "排序时反转顺序" },
    ["--reverse"] = { "排序时反转顺序" },
    ["-t"] = { "按修改时间排序，最新优先" },
    ["-S"] = { "按文件大小排序，最大优先" },
    ["--sort=size"] = { "按文件大小排序，最大优先" },
    ["-R"] = { "递归列出子目录" },
    ["--recursive"] = { "递归列出子目录" },
    ["-1"] = { "每行列出一个文件" },
    ["-F"] = { "向条目追加指示符（*/=>@| 之一）" },
    ["--classify"] = { "向条目追加指示符（*/=>@| 之一）" },
    ["-d"] = { "列出目录本身，而非其内容" },
    ["--directory"] = { "列出目录本身，而非其内容" },
    ["-i"] = { "打印每个文件的 inode 号" },
    ["--inode"] = { "打印每个文件的 inode 号" },
    ["-L"] = { "跟随符号链接，显示目标文件信息" },
    ["--dereference"] = { "跟随符号链接，显示目标文件信息" },
    ["-p"] = { "向目录追加 / 指示符" },
    ["--indicator-style=slash"] = { "向目录追加 / 指示符" },
    ["-s"] = { "打印每个文件的分配大小（以块为单位）" },
    ["--size"] = { "打印每个文件的分配大小（以块为单位）" },
    ["-X"] = { "按条目扩展名的字母顺序排序" },
    ["--sort=extension"] = { "按条目扩展名的字母顺序排序" },
    ["-U"] = { "不排序；按目录顺序列出条目" },
    ["--sort=none"] = { "不排序；按目录顺序列出条目" },
    ["-v"] = { "对文本中的版本号进行自然排序" },
    ["--sort=version"] = { "对文本中的版本号进行自然排序" },
    ["-c"] = { "与 -lt 一起使用：按 ctime 排序并显示" },
    ["-u"] = { "与 -lt 一起使用：按访问时间排序并显示" },
    ["--color"] = { " arg", "着色输出：auto, always, never" },
    ["--help"] = { "显示帮助并退出" },
    ["--version"] = { "输出版本信息并退出" },
})
:addflags({
    "-a", "--all",
    "-A", "--almost-all",
    "-l",
    "-h", "--human-readable",
    "-r", "--reverse",
    "-t",
    "-S", "--sort=size",
    "-R", "--recursive",
    "-1",
    "-F", "--classify",
    "-d", "--directory",
    "-i", "--inode",
    "-L", "--dereference",
    "-p", "--indicator-style=slash",
    "-s", "--size",
    "-X", "--sort=extension",
    "-U", "--sort=none",
    "-v", "--sort=version",
    "-c", "-u",
    "--color="..(clink.argmatcher():addarg({"auto", "always", "never"})),
    "--help", "--version",
})
